"""Generate each part's overview page and the site sidebar from docs/context/04-curriculum.md.

The curriculum doc is the single source of truth for which lessons exist and in
what order. Writing the part pages by hand would let the two drift apart, so we
generate them instead. A lesson shows as a link once its .qmd file exists, and
as "coming soon" until then.

Run from the repository root:  python3 course/_tools/generate_part_pages.py
CI runs it too and fails if the committed pages are out of date.
"""

import re
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
CURRICULUM = REPO_ROOT / "docs" / "context" / "04-curriculum.md"
COURSE = REPO_ROOT / "course"

# Folder name per part. Lesson files inside are named NN-<slug>.qmd.
PART_FOLDERS = {
    0: "part-0-start-here",
    1: "part-1-python",
    2: "part-2-computers-and-internet",
    3: "part-3-databases",
    4: "part-4-fastapi",
    5: "part-5-background-work",
    6: "part-6-atlas-rag",
    7: "part-7-production-aws",
    8: "part-8-atlas-agents",
    9: "part-9-scale-and-career",
}

PART_HEADING = re.compile(r"^## Part (\d+): (.+?) \((\d+)\)$")
LESSON_ROW = re.compile(r"^\| (\d+)\.(\d+) \| (.+?) \|(.*)\|$")
CHECKPOINT = re.compile(r"^\*\*Checkpoint \d+:\*\* (.+)$")


def parse_curriculum(text: str) -> list[dict]:
    """Turn the curriculum doc into a list of parts, each with its lessons."""
    parts: list[dict] = []
    current: dict | None = None

    for line in text.splitlines():
        heading = PART_HEADING.match(line)
        if heading:
            current = {
                "number": int(heading.group(1)),
                "title": heading.group(2),
                "intro": [],
                "lessons": [],
                "checkpoint": "",
            }
            parts.append(current)
            continue

        # Everything before the first part heading is the doc's own preamble.
        if current is None:
            continue

        # A level-2 heading that isn't a part ends the parts section.
        if line.startswith("## "):
            current = None
            continue

        lesson = LESSON_ROW.match(line)
        checkpoint = CHECKPOINT.match(line)
        is_table_line = line.startswith("|")

        if lesson:
            current["lessons"].append(
                {
                    "part": int(lesson.group(1)),
                    "number": int(lesson.group(2)),
                    "title": lesson.group(3),
                    "builds": lesson.group(4).strip(),
                }
            )
        elif checkpoint:
            current["checkpoint"] = checkpoint.group(1)
        elif line.strip() and not is_table_line:
            current["intro"].append(line)

    return parts


def find_lesson_file(folder: Path, lesson_number: int) -> Path | None:
    matches = sorted(folder.glob(f"{lesson_number:02d}-*.qmd"))
    if not matches:
        return None
    return matches[0]


def render_part_page(part: dict) -> str:
    folder = COURSE / PART_FOLDERS[part["number"]]
    lines = [
        "---",
        f'title: "Part {part["number"]}: {part["title"]}"',
        "---",
        "",
        "<!-- Generated by course/_tools/generate_part_pages.py. Edit the curriculum doc, not this file. -->",
        "",
    ]

    if part["intro"]:
        lines += [*part["intro"], ""]

    if part["checkpoint"]:
        lines += [f"**By the end of this part:** {part['checkpoint']}", ""]

    lines += [
        "| Lesson | Topic | Adds to the project |",
        "|---|---|---|",
    ]
    for lesson in part["lessons"]:
        lesson_id = f"{lesson['part']}.{lesson['number']}"
        lesson_file = find_lesson_file(folder, lesson["number"])
        if lesson_file is None:
            topic = f"{lesson['title']} *(coming soon)*"
        else:
            topic = f"[{lesson['title']}]({lesson_file.name})"
        lines.append(f"| {lesson_id} | {topic} | {lesson['builds']} |")

    return "\n".join(lines) + "\n"


def render_sidebar(parts: list[dict]) -> str:
    """Sidebar YAML listing each part's overview page and the lessons that exist."""
    lines = [
        "# Generated by course/_tools/generate_part_pages.py. Edit the curriculum doc, not this file.",
        "website:",
        "  sidebar:",
        "    style: docked",
        "    collapse-level: 1",
        "    contents:",
        "      - href: index.qmd",
        "        text: Welcome",
    ]
    for part in parts:
        folder_name = PART_FOLDERS[part["number"]]
        lines += [
            f'      - section: "Part {part["number"]}: {part["title"]}"',
            f"        href: {folder_name}/index.qmd",
            "        contents:",
        ]
        existing_lessons = []
        for lesson in part["lessons"]:
            lesson_file = find_lesson_file(COURSE / folder_name, lesson["number"])
            if lesson_file is not None:
                existing_lessons.append(f"          - {folder_name}/{lesson_file.name}")
        # An empty list keeps the section as a plain link to its overview page.
        lines += existing_lessons or ["          []"]
    return "\n".join(lines) + "\n"


def main() -> None:
    parts = parse_curriculum(CURRICULUM.read_text(encoding="utf-8"))

    # Guard against the doc's format changing silently and producing empty pages.
    if len(parts) != len(PART_FOLDERS):
        raise SystemExit(f"Expected {len(PART_FOLDERS)} parts, found {len(parts)}")

    for part in parts:
        folder = COURSE / PART_FOLDERS[part["number"]]
        folder.mkdir(exist_ok=True)
        (folder / "index.qmd").write_text(render_part_page(part), encoding="utf-8")

    (COURSE / "_sidebar.yml").write_text(render_sidebar(parts), encoding="utf-8")

    lesson_count = sum(len(part["lessons"]) for part in parts)
    print(f"Wrote {len(parts)} part pages covering {lesson_count} lessons")


if __name__ == "__main__":
    main()
